<#
.SYNOPSIS
  Feature x runtime table from every run's verdict (logs\*\verdict.txt, made by check-run.ps1).
  Writes checklists\runtime-matrix.md and prints it. A feature counts as verified on a runtime only with
  an automated PASS (SteamVR eye checks) or a dated human confirmation added to the "Human checks" table
  in that file by hand (that part is kept when the file is regenerated).

.EXAMPLE
  .\scripts\runtime-matrix.ps1            # uses existing verdicts
  .\scripts\runtime-matrix.ps1 -Recheck   # reruns check-run.ps1 on every run folder first
#>
[CmdletBinding()]
param([switch]$Recheck)
$ErrorActionPreference = 'Stop'
$scriptDir = if ($PSScriptRoot) { $PSScriptRoot } else { Split-Path -Parent $MyInvocation.MyCommand.Path }
$repo = (Resolve-Path (Join-Path $scriptDir '..')).Path
$md = Join-Path $repo 'checklists\runtime-matrix.md'
$rows = @()
$dirs = @(Get-ChildItem (Join-Path $repo 'logs') -Directory | Sort-Object Name)
# A run still in progress (game running) has no verdict yet: leave the newest folder out.
if ($dirs -and (Get-Process -Name 'VotV-Win64-Shipping' -ErrorAction SilentlyContinue)) { $dirs = $dirs[0..($dirs.Count - 2)] }
foreach ($d in $dirs) {
    $v = Join-Path $d.FullName 'verdict.txt'
    if ($Recheck -or -not (Test-Path $v)) {
        & powershell -NoProfile -ExecutionPolicy Bypass -File (Join-Path $scriptDir 'check-run.ps1') $d.FullName | Out-Null
    }
    if (-not (Test-Path $v)) { continue }
    $t = Get-Content $v
    if ($t[0] -notmatch '\| runtime (\S+) \| feature (.*)$') { continue }
    $rt = $Matches[1]; $feat = $Matches[2].Trim()
    $verdict = ($t | Select-String '^VERDICT (\S+)').Matches[0].Groups[1].Value
    $failed = ($t | Where-Object { $_ -like 'FAIL*' } | ForEach-Object { ($_ -split '\s+')[1] }) -join ', '
    $eyes = ($t | Where-Object { $_ -match '^\S+\s+eyes\s' } | ForEach-Object { ($_ -split '\s+')[0] })
    $rows += [pscustomobject]@{ Run = $d.Name; Runtime = $rt; Feature = $feat; Verdict = $verdict; Eyes = $eyes; Failed = $failed }
}

$keep = @()
if (Test-Path $md) {
    $old = Get-Content $md
    $i = [array]::IndexOf($old, '## Human checks')
    if ($i -ge 0) { $keep = $old[$i..($old.Count - 1)] }
}
if (-not $keep) {
    $keep = @('## Human checks', '',
        'Dated confirmations from the headset (user quote or playtest note). One row per feature and runtime.', '',
        '| Date | Runtime | Feature | Run | What the user said |', '|---|---|---|---|---|',
        '| 2026-11-26 23:41 | OpenXR | baseline (stereo, head tracking, playable) | 2026-11-27_00-28-34 | "more or less in the most basic of ways playable in vr, it looks great and runs great" |',
        '| 2026-11-26 23:48 | OpenXR | hud-pitch (`VR_DecoupledPitchUIAdjust=false`) | 2026-11-27_00-43-09 | "the HUD did stay put" |')
}

$out = @('# Runtime matrix', '',
    'Generated by `scripts\runtime-matrix.ps1` from each run''s `verdict.txt` (`scripts\check-run.ps1`); do not edit the',
    'tables above "Human checks". Rule (AGENTS.md): every feature is verified on OpenXR (Virtual Desktop) and on SteamVR.',
    'OpenXR runs cannot be eye-checked automatically, so they reach PASS only through the human table below;',
    'SteamVR runs are eye-checked from the compositor mirror with frame_check.py.', '',
    '## Latest automated verdict per feature and runtime', '',
    '| Feature | OpenXR | SteamVR |', '|---|---|---|')
foreach ($f in ($rows.Feature | Sort-Object -Unique)) {
    $cell = foreach ($rt in 'OpenXR', 'SteamVR') {
        $r = $rows | Where-Object { $_.Feature -eq $f -and $_.Runtime -eq $rt } | Select-Object -Last 1
        if ($r) { "$($r.Verdict) (eyes $($r.Eyes); $($r.Run))" } else { 'not run' }
    }
    $out += "| $f | $($cell[0]) | $($cell[1]) |"
}
$out += @('', '## All runs', '', '| Run | Runtime | Feature | Verdict | Eyes | Failed checks |', '|---|---|---|---|---|---|')
foreach ($r in $rows) { $out += "| $($r.Run) | $($r.Runtime) | $($r.Feature) | $($r.Verdict) | $($r.Eyes) | $($r.Failed) |" }
$out += ''
$out += $keep
$out | Set-Content -Path $md -Encoding utf8
$out | ForEach-Object { Write-Host $_ }
